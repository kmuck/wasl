//! Helper functions of the module (§ 12.8): string comparison and concatenation, UTF-8
//! validation, decoding and encoding, `char.from_u32`, list copies, integer overflow.
//!
//! Strings are always valid UTF-8 (literals, `string.from_bytes` validates, the
//! component boundary validates), and lists of chars only hold Unicode scalar values: the
//! decoder and the encoder do not check their input.

use wasm_encoder::{BlockType, Function, HeapType, Instruction, StorageType, ValType};

use super::boundary::Boundary;
use super::{ModuleCx, field, ref_type};
use crate::types::{DeclKind, Type, TypeKind};

use Instruction as I;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(super) enum Helper {
    /// `(string, string) -> bool`
    StrEq,
    /// `(string, string) -> string`
    Concat,
    /// `string.from_bytes`: `(list<u8>) -> option<string>`
    FromBytes,
    /// `string.chars`: `(string) -> list<char>`
    Chars,
    /// `string.from_chars`: `(list<char>) -> string`
    FromChars,
    /// `char.from_u32`: `(u32) -> option<char>`
    CharFromU32,
    /// `list.copy` and `list.freeze` on an array type.
    Copy(u32),
    /// `T.to_string`: `(i64) -> string`, the decimal form of an integer extended to 64
    /// bits, read as signed or not.
    IntToString { signed: bool },
    /// `T.parse` for the integer type `T`: `(string) -> option<T>`.
    IntParse(Type),
    /// `(i64, i64) -> i32`: whether the exact product does not fit in a `u64`
    /// (`signed: false`) or an `s64`, when an operand does not fit in 32 bits (§ 12.9).
    MulOverflow64 { signed: bool },
    /// `==` on a type that is neither a scalar nor a string (§ 8.3): `(T', T') -> bool`,
    /// comparing the contents, depth first, until the first difference.
    Eq(Type),
    /// The boundary helpers of § 13, generated by [`super::boundary`].
    Boundary(Boundary),
}

/// `local.get`
fn get(l: u32) -> Instruction<'static> {
    I::LocalGet(l)
}

/// `local = local + 1`
fn incr(l: u32) -> [Instruction<'static>; 4] {
    [get(l), I::I32Const(1), I::I32Add, I::LocalSet(l)]
}

impl Helper {
    /// Parameters, results and body of the helper.
    pub(super) fn generate(self, cx: &mut ModuleCx) -> (Vec<ValType>, Vec<ValType>, Function) {
        if let Helper::Boundary(helper) = self {
            return helper.generate(cx);
        }
        let bytes = cx.heap(Type::STRING);
        let string = ref_type(bytes, false);
        let (params, results, locals, code) = match self {
            Helper::StrEq => (
                vec![string, string],
                vec![ValType::I32],
                vec![ValType::I32; 2],
                str_eq(bytes),
            ),
            Helper::Concat => (
                vec![string, string],
                vec![string],
                vec![string],
                concat(bytes),
            ),
            Helper::FromBytes => {
                let mut locals = vec![ValType::I32; 7];
                locals.push(string);
                (
                    vec![string],
                    vec![ref_type(bytes, true)],
                    locals,
                    from_bytes(bytes),
                )
            }
            Helper::Chars => {
                let chars = cx.array(StorageType::Val(ValType::I32));
                let mut locals = vec![ValType::I32; 4];
                locals.push(ref_type(chars, false));
                (
                    vec![string],
                    vec![ref_type(chars, false)],
                    locals,
                    decode(bytes, chars),
                )
            }
            Helper::FromChars => {
                let chars = cx.array(StorageType::Val(ValType::I32));
                let mut locals = vec![ValType::I32; 4];
                locals.push(string);
                locals.push(ValType::I32);
                (
                    vec![ref_type(chars, false)],
                    vec![string],
                    locals,
                    encode(bytes, chars),
                )
            }
            Helper::CharFromU32 => {
                let boxed = cx.immutable_struct(vec![field(ValType::I32, false)]);
                (
                    vec![ValType::I32],
                    vec![ref_type(boxed, true)],
                    Vec::new(),
                    char_from_u32(boxed),
                )
            }
            Helper::IntToString { signed } => (
                vec![ValType::I64],
                vec![string],
                vec![ValType::I32, ValType::I32, ValType::I64, string],
                int_to_string(bytes, signed),
            ),
            Helper::IntParse(int) => {
                let boxed = cx.option_heap(int);
                (
                    vec![string],
                    vec![ref_type(boxed, true)],
                    vec![
                        ValType::I32,
                        ValType::I32,
                        ValType::I32,
                        ValType::I64,
                        ValType::I64,
                    ],
                    int_parse(bytes, boxed, int),
                )
            }
            Helper::Copy(array) => {
                let list = ref_type(array, false);
                let storage = cx.rec[array as usize].composite_type.inner.clone();
                let wasm_encoder::CompositeInnerType::Array(ty) = storage else {
                    unreachable!("an array type")
                };
                let defaultable = !matches!(
                    ty.0.element_type,
                    StorageType::Val(ValType::Ref(r)) if !r.nullable
                );
                (
                    vec![list],
                    vec![list],
                    vec![ValType::I32, list],
                    copy(array, defaultable),
                )
            }
            Helper::MulOverflow64 { signed } => (
                vec![ValType::I64, ValType::I64],
                vec![ValType::I32],
                vec![ValType::I64],
                mul_overflow_64(signed),
            ),
            Helper::Eq(ty) => {
                let val = cx.val(ty);
                (
                    vec![val, val],
                    vec![ValType::I32],
                    vec![ValType::I32; 2],
                    eq(cx, ty),
                )
            }
            Helper::Boundary(_) => unreachable!("generated above"),
        };
        let mut function = Function::new_with_locals_types(locals);
        for instr in &code {
            function.instruction(instr);
        }
        function.instruction(&I::End);
        (params, results, function)
    }
}

/// `a == b`: same length, then same bytes.
/// Locals: a = 0, b = 1, n = 2, i = 3.
fn str_eq(bytes: u32) -> Vec<Instruction<'static>> {
    let mut c = vec![
        get(0),
        I::ArrayLen,
        I::LocalTee(2),
        get(1),
        I::ArrayLen,
        I::I32Ne,
        I::If(BlockType::Empty),
        I::I32Const(0),
        I::Return,
        I::End,
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(3),
        get(2),
        I::I32GeU,
        I::BrIf(1),
        get(0),
        get(3),
        I::ArrayGetU(bytes),
        get(1),
        get(3),
        I::ArrayGetU(bytes),
        I::I32Ne,
        I::If(BlockType::Empty),
        I::I32Const(0),
        I::Return,
        I::End,
    ];
    c.extend(incr(3));
    c.extend([I::Br(0), I::End, I::End, I::I32Const(1)]);
    c
}

/// `a + b` on strings. Locals: a = 0, b = 1, r = 2.
fn concat(bytes: u32) -> Vec<Instruction<'static>> {
    let copy = I::ArrayCopy {
        array_type_index_dst: bytes,
        array_type_index_src: bytes,
    };
    vec![
        get(0),
        I::ArrayLen,
        get(1),
        I::ArrayLen,
        I::I32Add,
        I::ArrayNewDefault(bytes),
        I::LocalSet(2),
        // r[0..] = a
        get(2),
        I::I32Const(0),
        get(0),
        I::I32Const(0),
        get(0),
        I::ArrayLen,
        copy.clone(),
        // r[len(a)..] = b
        get(2),
        get(0),
        I::ArrayLen,
        get(1),
        I::I32Const(0),
        get(1),
        I::ArrayLen,
        copy,
        get(2),
    ]
}

/// `list.copy`, `list.freeze`: a new array of the same length, then `array.copy`. An
/// array of non-nullable references has no default value: it is created filled with its
/// first element. Locals: xs = 0, n = 1, r = 2.
fn copy(array: u32, defaultable: bool) -> Vec<Instruction<'static>> {
    let mut c = vec![get(0), I::ArrayLen, I::LocalTee(1)];
    if defaultable {
        c.push(I::ArrayNewDefault(array));
    } else {
        c.extend([
            I::I32Eqz,
            I::If(BlockType::Result(ref_type(array, false))),
            I::ArrayNewFixed {
                array_type_index: array,
                array_size: 0,
            },
            I::Else,
            get(0),
            I::I32Const(0),
            I::ArrayGet(array),
            get(1),
            I::ArrayNew(array),
            I::End,
        ]);
    }
    c.extend([
        I::LocalSet(2),
        get(2),
        I::I32Const(0),
        get(0),
        I::I32Const(0),
        get(1),
        I::ArrayCopy {
            array_type_index_dst: array,
            array_type_index_src: array,
        },
        get(2),
    ]);
    c
}

/// `T.to_string(n)`: the digits of the magnitude of `n`, written from the last one, after
/// a `-` when `n` is negative. Locals: n = 0, negative = 1, i = 2, rest = 3, r = 4.
///
/// The magnitude of a negative `n` is `0 - n`, read as unsigned: it is exact for the
/// smallest `s64` too.
fn int_to_string(bytes: u32, signed: bool) -> Vec<Instruction<'static>> {
    let mut code = Vec::new();
    if signed {
        code.extend([
            get(0),
            I::I64Const(0),
            I::I64LtS,
            I::LocalTee(1),
            I::If(BlockType::Empty),
            I::I64Const(0),
            get(0),
            I::I64Sub,
            I::LocalSet(0),
            I::End,
        ]);
    }
    code.extend([
        // i = the number of digits, plus one for the sign
        get(1),
        I::LocalSet(2),
        get(0),
        I::LocalSet(3),
        I::Loop(BlockType::Empty),
    ]);
    code.extend(incr(2));
    code.extend([
        get(3),
        I::I64Const(10),
        I::I64DivU,
        I::LocalTee(3),
        I::I64Const(0),
        I::I64Ne,
        I::BrIf(0),
        I::End,
        get(2),
        I::ArrayNewDefault(bytes),
        I::LocalSet(4),
        // the digits, from the last one
        I::Loop(BlockType::Empty),
        get(4),
        get(2),
        I::I32Const(1),
        I::I32Sub,
        I::LocalTee(2),
        get(0),
        I::I64Const(10),
        I::I64RemU,
        I::I32WrapI64,
        I::I32Const('0' as i32),
        I::I32Add,
        I::ArraySet(bytes),
        get(0),
        I::I64Const(10),
        I::I64DivU,
        I::LocalTee(0),
        I::I64Const(0),
        I::I64Ne,
        I::BrIf(0),
        I::End,
        get(1),
        I::If(BlockType::Empty),
        get(4),
        I::I32Const(0),
        I::I32Const('-' as i32),
        I::ArraySet(bytes),
        I::End,
        get(4),
    ]);
    code
}

/// `T.parse(s)`: the integer that `T.to_string` writes as `s`, boxed, or `none`: an
/// optional `-` for a signed type, then digits without a leading zero, whose value fits
/// in `T`. Locals: s = 0, i = 1, len = 2, negative = 3, limit = 4, value = 5.
///
/// `limit` is the largest magnitude allowed: the value stays below it at every digit, so
/// it never overflows the `i64` that holds it.
fn int_parse(bytes: u32, boxed: u32, int: Type) -> Vec<Instruction<'static>> {
    let none = || [I::RefNull(HeapType::Concrete(boxed)), I::Return];
    let digit = [
        get(0),
        get(1),
        I::ArrayGetU(bytes),
        I::I32Const('0' as i32),
        I::I32Sub,
    ];
    let bits = int.bits();
    let max: u64 = if int.is_signed() {
        (1 << (bits - 1)) - 1
    } else if bits == 64 {
        u64::MAX
    } else {
        (1 << bits) - 1
    };
    let mut code = vec![
        get(0),
        I::ArrayLen,
        I::LocalTee(2),
        I::I32Eqz,
        I::If(BlockType::Empty),
    ];
    code.extend(none());
    code.extend([I::End, I::I64Const(max as i64), I::LocalSet(4)]);
    if int.is_signed() {
        // `-`: one more for the limit, and at least one digit after it
        code.extend([
            get(0),
            I::I32Const(0),
            I::ArrayGetU(bytes),
            I::I32Const('-' as i32),
            I::I32Eq,
            I::If(BlockType::Empty),
            I::I32Const(1),
            I::LocalSet(3),
            I::I32Const(1),
            I::LocalSet(1),
            get(4),
            I::I64Const(1),
            I::I64Add,
            I::LocalSet(4),
            get(2),
            I::I32Const(1),
            I::I32Eq,
            I::If(BlockType::Empty),
        ]);
        code.extend(none());
        code.extend([I::End, I::End]);
    }
    // a leading zero is only the number zero, without sign
    code.extend(digit.clone());
    code.extend([
        I::I32Eqz,
        get(2),
        I::I32Const(1),
        I::I32Ne,
        I::I32And,
        I::If(BlockType::Empty),
    ]);
    code.extend(none());
    code.extend([I::End, I::Loop(BlockType::Empty)]);
    // the digit, on the stack as an i64, once it is checked
    code.extend(digit.clone());
    code.extend([I::I32Const(9), I::I32GtU, I::If(BlockType::Empty)]);
    code.extend(none());
    code.push(I::End);
    // value > (limit - digit) / 10: the next value would pass the limit
    code.extend([get(5), get(4)]);
    code.extend(digit.clone());
    code.extend([
        I::I64ExtendI32U,
        I::I64Sub,
        I::I64Const(10),
        I::I64DivU,
        I::I64GtU,
        I::If(BlockType::Empty),
    ]);
    code.extend(none());
    code.extend([I::End, get(5), I::I64Const(10), I::I64Mul]);
    code.extend(digit);
    code.extend([I::I64ExtendI32U, I::I64Add, I::LocalSet(5)]);
    code.extend(incr(1));
    code.extend([get(1), get(2), I::I32LtU, I::BrIf(0), I::End]);
    // the value, with its sign, in the Wasm type of `T`
    code.extend([
        get(3),
        I::If(BlockType::Result(ValType::I64)),
        I::I64Const(0),
        get(5),
        I::I64Sub,
        I::Else,
        get(5),
        I::End,
    ]);
    if bits < 64 {
        code.push(I::I32WrapI64);
    }
    code.push(I::StructNew(boxed));
    code
}

/// `char.from_u32(n)`: `n` boxed if it is a Unicode scalar value (not a surrogate, at
/// most U+10FFFF), `none` otherwise. Locals: n = 0.
fn char_from_u32(boxed: u32) -> Vec<Instruction<'static>> {
    vec![
        get(0),
        I::I32Const(0xD800),
        I::I32LtU,
        get(0),
        I::I32Const(0xE000),
        I::I32GeU,
        get(0),
        I::I32Const(0x10FFFF),
        I::I32LeU,
        I::I32And,
        I::I32Or,
        I::If(BlockType::Result(ref_type(boxed, true))),
        get(0),
        I::StructNew(boxed),
        I::Else,
        I::RefNull(HeapType::Concrete(boxed)),
        I::End,
    ]
}

/// Whether `a * b` overflows a 64-bit integer, for operands that do not both fit in 32
/// bits (the generated code tests that case inline). Locals: a = 0, b = 1, r = 2.
///
/// The product overflowed exactly when `r / a != b` for `a != 0`, `r` being the wrapped
/// product. The signed case `a == -1` is tested apart, since `r / -1` traps when `r` is
/// `i64::MIN`.
fn mul_overflow_64(signed: bool) -> Vec<Instruction<'static>> {
    let mut c = vec![
        get(0),
        get(1),
        I::I64Mul,
        I::LocalSet(2),
        get(0),
        I::I64Eqz,
        I::If(BlockType::Result(ValType::I32)),
        I::I32Const(0),
        I::Else,
    ];
    if signed {
        c.extend([
            get(0),
            I::I64Const(-1),
            I::I64Eq,
            I::If(BlockType::Result(ValType::I32)),
            // -1 * b overflows only for b = i64::MIN.
            get(1),
            I::I64Const(i64::MIN),
            I::I64Eq,
            I::Else,
            get(2),
            get(0),
            I::I64DivS,
            get(1),
            I::I64Ne,
            I::End,
        ]);
    } else {
        c.extend([get(2), get(0), I::I64DivU, get(1), I::I64Ne]);
    }
    c.push(I::End);
    c
}

/// `string.from_bytes(b)`: validates UTF-8 (Unicode table 3-7: no overlong form, no
/// surrogate, nothing above U+10FFFF), then copies the bytes.
/// Locals: b = 0, n = 1, i = 2, c = 3, need = 4, lo = 5, hi = 6, j = 7, r = 8.
fn from_bytes(bytes: u32) -> Vec<Instruction<'static>> {
    let invalid = |c: &mut Vec<Instruction<'static>>| {
        c.extend([
            I::If(BlockType::Empty),
            I::RefNull(HeapType::Concrete(bytes)),
            I::Return,
            I::End,
        ])
    };
    // `need` continuation bytes, the first one in [lo, hi].
    let sequence = |need: i32, lo: [i32; 2], hi: [i32; 2]| {
        vec![
            I::I32Const(need),
            I::LocalSet(4),
            // lo = c == lo[0] ? lo[1] : 0x80
            I::I32Const(lo[1]),
            I::I32Const(0x80),
            get(3),
            I::I32Const(lo[0]),
            I::I32Eq,
            I::Select,
            I::LocalSet(5),
            // hi = c == hi[0] ? hi[1] : 0xBF
            I::I32Const(hi[1]),
            I::I32Const(0xBF),
            get(3),
            I::I32Const(hi[0]),
            I::I32Eq,
            I::Select,
            I::LocalSet(6),
        ]
    };

    let mut c = vec![
        get(0),
        I::ArrayLen,
        I::LocalSet(1),
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(2),
        get(1),
        I::I32GeU,
        I::BrIf(1),
        get(0),
        get(2),
        I::ArrayGetU(bytes),
        I::LocalTee(3),
        I::I32Const(0x80),
        I::I32LtU,
        I::If(BlockType::Empty),
    ];
    // ASCII: next byte
    c.extend(incr(2));
    c.extend([I::Br(1), I::End]);
    c.extend([get(3), I::I32Const(0xC2), I::I32LtU]);
    invalid(&mut c);
    c.extend([
        get(3),
        I::I32Const(0xE0),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    // C2..DF: one continuation byte (0xFF never equals c: no special case)
    c.extend(sequence(1, [0xFF, 0x80], [0xFF, 0xBF]));
    c.extend([
        I::Else,
        get(3),
        I::I32Const(0xF0),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    // E0: A0..BF; ED: 80..9F; others 80..BF
    c.extend(sequence(2, [0xE0, 0xA0], [0xED, 0x9F]));
    c.extend([I::Else, get(3), I::I32Const(0xF5), I::I32GeU]);
    invalid(&mut c);
    // F0: 90..BF; F4: 80..8F; others 80..BF
    c.extend(sequence(3, [0xF0, 0x90], [0xF4, 0x8F]));
    c.extend([I::End, I::End]);
    // i + need < n, that is need < n - i (n > i here)
    c.extend([get(4), get(1), get(2), I::I32Sub, I::I32GeU]);
    invalid(&mut c);
    // First continuation byte in [lo, hi]
    c.extend([
        get(0),
        get(2),
        I::I32Const(1),
        I::I32Add,
        I::ArrayGetU(bytes),
        I::LocalTee(3),
        get(5),
        I::I32LtU,
        get(3),
        get(6),
        I::I32GtU,
        I::I32Or,
    ]);
    invalid(&mut c);
    // The others in 80..BF
    c.extend([
        I::I32Const(2),
        I::LocalSet(7),
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(7),
        get(4),
        I::I32GtU,
        I::BrIf(1),
        get(0),
        get(2),
        get(7),
        I::I32Add,
        I::ArrayGetU(bytes),
        I::I32Const(0xC0),
        I::I32And,
        I::I32Const(0x80),
        I::I32Ne,
    ]);
    invalid(&mut c);
    c.extend(incr(7));
    c.extend([I::Br(0), I::End, I::End]);
    // i = i + need + 1
    c.extend([
        get(2),
        get(4),
        I::I32Add,
        I::I32Const(1),
        I::I32Add,
        I::LocalSet(2),
        I::Br(0),
        I::End,
        I::End,
    ]);
    // Copy: `b` may be a `list<mut u8>`, which can change afterwards.
    c.extend([
        get(1),
        I::ArrayNewDefault(bytes),
        I::LocalSet(8),
        get(8),
        I::I32Const(0),
        get(0),
        I::I32Const(0),
        get(1),
        I::ArrayCopy {
            array_type_index_dst: bytes,
            array_type_index_src: bytes,
        },
        get(8),
    ]);
    c
}

/// `string.chars(s)`: counts the chars (the bytes that are not continuation bytes), then
/// decodes them. Locals: s = 0, n = 1, i = 2, k = 3, c = 4, r = 5.
fn decode(bytes: u32, chars: u32) -> Vec<Instruction<'static>> {
    // c = c << 6 | (s[i + offset] & 0x3F)
    let cont = |offset: i32| {
        [
            get(4),
            I::I32Const(6),
            I::I32Shl,
            get(0),
            get(2),
            I::I32Const(offset),
            I::I32Add,
            I::ArrayGetU(bytes),
            I::I32Const(0x3F),
            I::I32And,
            I::I32Or,
            I::LocalSet(4),
        ]
    };
    // Sequence of `len` bytes: keep the payload bits of the first one, then the
    // continuation bytes.
    let sequence = |len: i32, mask: i32| {
        let mut c = vec![get(4), I::I32Const(mask), I::I32And, I::LocalSet(4)];
        for offset in 1..len {
            c.extend(cont(offset));
        }
        c.extend([get(2), I::I32Const(len), I::I32Add, I::LocalSet(2)]);
        c
    };

    let mut c = vec![
        get(0),
        I::ArrayLen,
        I::LocalSet(1),
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(2),
        get(1),
        I::I32GeU,
        I::BrIf(1),
        // k += (s[i] & 0xC0) != 0x80
        get(0),
        get(2),
        I::ArrayGetU(bytes),
        I::I32Const(0xC0),
        I::I32And,
        I::I32Const(0x80),
        I::I32Ne,
        get(3),
        I::I32Add,
        I::LocalSet(3),
    ];
    c.extend(incr(2));
    c.extend([
        I::Br(0),
        I::End,
        I::End,
        get(3),
        I::ArrayNewDefault(chars),
        I::LocalSet(5),
        I::I32Const(0),
        I::LocalSet(2),
        I::I32Const(0),
        I::LocalSet(3),
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(2),
        get(1),
        I::I32GeU,
        I::BrIf(1),
        get(0),
        get(2),
        I::ArrayGetU(bytes),
        I::LocalTee(4),
        I::I32Const(0x80),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    c.extend(incr(2));
    c.extend([
        I::Else,
        get(4),
        I::I32Const(0xE0),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    c.extend(sequence(2, 0x1F));
    c.extend([
        I::Else,
        get(4),
        I::I32Const(0xF0),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    c.extend(sequence(3, 0x0F));
    c.push(I::Else);
    c.extend(sequence(4, 0x07));
    c.extend([I::End, I::End, I::End]);
    // r[k] = c; k += 1
    c.extend([get(5), get(3), get(4), I::ArraySet(chars)]);
    c.extend(incr(3));
    c.extend([I::Br(0), I::End, I::End, get(5)]);
    c
}

/// `string.from_chars(cs)`: computes the length in bytes, then encodes.
/// Locals: cs = 0, n = 1, i = 2, len = 3, c = 4, r = 5, k = 6.
fn encode(bytes: u32, chars: u32) -> Vec<Instruction<'static>> {
    // r[k] = prefix | (c >> shift) & mask; k += 1
    let put = |shift: i32, mask: i32, prefix: i32| {
        let mut c = vec![get(5), get(6), get(4)];
        if shift > 0 {
            c.extend([I::I32Const(shift), I::I32ShrU]);
        }
        if mask != 0xFF {
            c.extend([I::I32Const(mask), I::I32And]);
        }
        if prefix != 0 {
            c.extend([I::I32Const(prefix), I::I32Or]);
        }
        c.push(I::ArraySet(bytes));
        c.extend(incr(6));
        c
    };

    let mut c = vec![
        get(0),
        I::ArrayLen,
        I::LocalSet(1),
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(2),
        get(1),
        I::I32GeU,
        I::BrIf(1),
        get(0),
        get(2),
        I::ArrayGet(chars),
        I::LocalSet(4),
        // len += 1 + (c >= 0x80) + (c >= 0x800) + (c >= 0x10000)
        get(3),
        I::I32Const(1),
        I::I32Add,
    ];
    for bound in [0x80, 0x800, 0x10000] {
        c.extend([get(4), I::I32Const(bound), I::I32GeU, I::I32Add]);
    }
    c.push(I::LocalSet(3));
    c.extend(incr(2));
    c.extend([
        I::Br(0),
        I::End,
        I::End,
        get(3),
        I::ArrayNewDefault(bytes),
        I::LocalSet(5),
        I::I32Const(0),
        I::LocalSet(2),
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        get(2),
        get(1),
        I::I32GeU,
        I::BrIf(1),
        get(0),
        get(2),
        I::ArrayGet(chars),
        I::LocalTee(4),
        I::I32Const(0x80),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    c.extend(put(0, 0xFF, 0));
    c.extend([
        I::Else,
        get(4),
        I::I32Const(0x800),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    c.extend(put(6, 0xFF, 0xC0));
    c.extend(put(0, 0x3F, 0x80));
    c.extend([
        I::Else,
        get(4),
        I::I32Const(0x10000),
        I::I32LtU,
        I::If(BlockType::Empty),
    ]);
    c.extend(put(12, 0xFF, 0xE0));
    c.extend(put(6, 0x3F, 0x80));
    c.extend(put(0, 0x3F, 0x80));
    c.push(I::Else);
    c.extend(put(18, 0xFF, 0xF0));
    c.extend(put(12, 0x3F, 0x80));
    c.extend(put(6, 0x3F, 0x80));
    c.extend(put(0, 0x3F, 0x80));
    c.extend([I::End, I::End, I::End]);
    c.extend(incr(2));
    c.extend([I::Br(0), I::End, I::End, get(5)]);
    c
}

/// Compares two values of type `ty` on the stack, and leaves whether they are equal.
fn eq_values(cx: &mut ModuleCx, ty: Type) -> Vec<Instruction<'static>> {
    if ty == Type::STRING {
        return vec![I::Call(cx.helper(Helper::StrEq))];
    }
    match cx.val(ty) {
        ValType::I64 => vec![I::I64Eq],
        ValType::F32 => vec![I::F32Eq],
        ValType::F64 => vec![I::F64Eq],
        // Bools, normalized small integers, chars, enums and flags.
        ValType::I32 => vec![I::I32Eq],
        _ => vec![I::Call(cx.helper(Helper::Eq(ty)))],
    }
}

/// `return 0` when the comparison on the stack is false.
fn unless_equal() -> [Instruction<'static>; 5] {
    [
        I::I32Eqz,
        I::If(BlockType::Empty),
        I::I32Const(0),
        I::Return,
        I::End,
    ]
}

/// `a == b` on a type that is neither a scalar nor a string (§ 8.3). Locals: a = 0,
/// b = 1, n = 2, i = 3.
fn eq(cx: &mut ModuleCx, ty: Type) -> Vec<Instruction<'static>> {
    let types = cx.types;
    let mut c = Vec::new();
    // A tuple or a record: the same fields, in order.
    let fields = match (types.kind(ty), types.decl(ty)) {
        (TypeKind::Tuple(elems), _) => Some(elems.clone()),
        (_, Some((_, d))) if matches!(d.kind, DeclKind::Record(_)) => Some(types.children(ty)),
        _ => None,
    };
    if let Some(fields) = fields {
        let s = cx.heap(ty);
        for (k, f) in fields.into_iter().enumerate() {
            let read = I::StructGet {
                struct_type_index: s,
                field_index: k as u32,
            };
            c.extend([get(0), read.clone(), get(1), read]);
            c.extend(eq_values(cx, f));
            c.extend(unless_equal());
        }
        c.push(I::I32Const(1));
        return c;
    }
    match types.kind(ty) {
        TypeKind::List { elem, .. } => {
            let elem = *elem;
            let array = cx.heap(ty);
            let read = match cx.storage(elem) {
                StorageType::I8 | StorageType::I16 => I::ArrayGetU(array),
                StorageType::Val(_) => I::ArrayGet(array),
            };
            c.extend([
                get(0),
                I::ArrayLen,
                I::LocalTee(2),
                get(1),
                I::ArrayLen,
                I::I32Ne,
                I::If(BlockType::Empty),
                I::I32Const(0),
                I::Return,
                I::End,
                I::Block(BlockType::Empty),
                I::Loop(BlockType::Empty),
                get(3),
                get(2),
                I::I32GeU,
                I::BrIf(1),
                get(0),
                get(3),
                read.clone(),
                get(1),
                get(3),
                read,
            ]);
            c.extend(eq_values(cx, elem));
            c.extend(unless_equal());
            c.extend(incr(3));
            c.extend([I::Br(0), I::End, I::End, I::I32Const(1)]);
        }
        TypeKind::Option(inner) => {
            let inner = *inner;
            // Both `none`, or one of them only.
            c.extend([
                get(0),
                I::RefIsNull,
                I::If(BlockType::Empty),
                get(1),
                I::RefIsNull,
                I::Return,
                I::End,
                get(1),
                I::RefIsNull,
                I::If(BlockType::Empty),
                I::I32Const(0),
                I::Return,
                I::End,
            ]);
            if cx.boxed(inner) {
                let boxed = cx.option_heap(inner);
                let unbox = I::StructGet {
                    struct_type_index: boxed,
                    field_index: 0,
                };
                c.extend([get(0), unbox.clone(), get(1), unbox]);
            } else {
                c.extend([get(0), I::RefAsNonNull, get(1), I::RefAsNonNull]);
            }
            c.extend(eq_values(cx, inner));
        }
        _ => {
            // A variant or a result (§ 12.6): the same tag, then the same payload.
            let payloads: Vec<Option<Type>> = match types.kind(ty) {
                TypeKind::Result { ok, err } => vec![*ok, *err],
                _ => match types.decl(ty) {
                    Some((_, d)) => match &d.kind {
                        DeclKind::Variant(cases) => cases.iter().map(|c| c.payload).collect(),
                        _ => unreachable!("an equatable heap type"),
                    },
                    None => unreachable!("an equatable heap type"),
                },
            };
            let base = cx.heap(ty);
            let tag = I::StructGet {
                struct_type_index: base,
                field_index: 0,
            };
            c.extend([get(0), tag.clone(), get(1), tag.clone(), I::I32Eq]);
            c.extend(unless_equal());
            for (k, payload) in payloads.into_iter().enumerate() {
                let Some(p) = payload else { continue };
                let case = cx.case_type(ty, k as u32);
                let read = [
                    I::RefCastNonNull(HeapType::Concrete(case)),
                    I::StructGet {
                        struct_type_index: case,
                        field_index: 1,
                    },
                ];
                c.extend([
                    get(0),
                    tag.clone(),
                    I::I32Const(k as i32),
                    I::I32Eq,
                    I::If(BlockType::Empty),
                    get(0),
                ]);
                c.extend(read.clone());
                c.push(get(1));
                c.extend(read);
                c.extend(eq_values(cx, p));
                c.extend([I::Return, I::End]);
            }
            c.push(I::I32Const(1));
        }
    }
    c
}
